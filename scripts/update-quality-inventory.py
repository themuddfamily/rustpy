#!/usr/bin/env python3
"""Source inventory only: declared #[test] sites are not executed-test counts."""
from pathlib import Path
import re
import tomllib
ROOT = Path(__file__).resolve().parent.parent

def inventory(root):
    rows = []
    for manifest in sorted((root / 'crates').glob('*/Cargo.toml')):
        package = tomllib.loads(manifest.read_text())['package']['name']
        sources = list(manifest.parent.rglob('*.rs'))
        # Never traverse a generated build tree or a vendored typeshed source.
        sources = [p for p in sources if not any(s in ('target', 'typeshed') for s in p.relative_to(manifest.parent).parts)]
        sites = sum(len(re.findall(r'#\[test\]', p.read_text(encoding='utf-8'))) for p in sources)
        integration = sum(1 for p in (manifest.parent / 'tests').glob('*.rs'))
        rows.append((package, sites, integration))
    return rows

if __name__ == '__main__':
    lines = ['# Source test inventory\n\n',
        'Generated by `scripts/update-quality-inventory.py`. Counts are textual `#[test]`\n',
        'sites and top-level integration-test files, **not executed tests, coverage or pass counts**.\n',
        'Conditional compilation, ignored tests, macros and platform dependencies can change\n',
        'the executable inventory. Use `cargo test -- --list` and actual runs at final verification.\n',
        'A zero count requires triage; do not treat a smoke build as unit coverage.\n\n',
        '| Crate | Declared test sites | Integration files |\n|---|---:|---:|\n']
    for name, sites, integration in inventory(ROOT):
        lines.append(f'| `{name}` | {sites} | {integration} |\n')
    (ROOT / 'docs/quality-inventory.md').write_text(''.join(lines), encoding='utf-8')
