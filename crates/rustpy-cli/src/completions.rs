const POWERSHELL: &str = r#"# PowerShell completion for rustpy (generated by 'rustpy completions powershell')
Register-ArgumentCompleter -Native -CommandName rustpy, rustpy.exe, rustpy.cmd -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $commands = @('http', 'test', 'diff', 'merge', 'format', 'inspect', 'lsp', 'remote-server', 'completions', 'install-launcher', 'diagnostics', 'help')
    $global = @('--headless', '--config-dir', '--system-dir', '--log-dir', '--disable-plugins', '--verbose', '--help', '--version')
    $options = @{
        'test' = @('--project', '--framework', '--interpreter', '--cwd', '--python-option', '--env', '--no-inherit-env', '--timeout', '--json', '--junit', '--', '-h')
        'http' = @('--env', '--request', '--var', '--timeout', '--json', '-h')
        'format' = @('-h', '-s', '-settings', '-r', '-R', '-m', '-mask', '-charset', '-d', '-dry', '-allowDefaults')
        'inspect' = @('-h', '-d', '-changes', '-format', '-v0', '-v1', '-v2', '-profileName', '-profilePath')
        'diff' = @('-h')
        'merge' = @('-h')
        'install-launcher' = @('--force', '-h')
        'diagnostics' = @('--output', '-h')
    }
    $values = @{
        'completions' = @('bash', 'zsh', 'fish', 'powershell')
        'help' = @('http', 'test', 'diff', 'merge', 'format', 'inspect', 'lsp', 'remote-server', 'completions', 'install-launcher', 'diagnostics')
        '--framework' = @('auto', 'pytest', 'unittest', 'doctest', 'nose', 'nose2', 'trial', 'tox', 'behave', 'lettuce')
        '-format' = @('xml', 'json', 'plain', 'sarif')
        '-charset' = @('UTF-8', 'UTF-16', 'UTF-16LE', 'UTF-16BE', 'ISO-8859-1', 'US-ASCII')
    }
    $words = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.ToString() })
    if ($wordToComplete -ne '' -and $words.Count -gt 0) { $words = @($words | Select-Object -SkipLast 1) }
    $command = $null
    for ($i = 0; $i -lt $words.Count; $i++) {
        $w = $words[$i]
        if ($w -in @('--config-dir', '--system-dir', '--log-dir', '--line', '-l', '--column', '-c')) { $i++; continue }
        if ($w.StartsWith('-')) { continue }
        $command = $w
        break
    }
    $previous = if ($words.Count -gt 0) { $words[-1] } else { '' }
    $candidates = @()
    if ($values.ContainsKey($previous)) {
        $candidates = $values[$previous]
    } elseif ($null -ne $command -and $values.ContainsKey($command)) {
        $candidates = $values[$command]
    } elseif ($wordToComplete.StartsWith('-')) {
        if ($null -eq $command) { $candidates = $global + @('--line', '--column', '--wait', '--new-window', '--software-rendering') }
        elseif ($options.ContainsKey($command)) { $candidates = $options[$command] + $global }
    } elseif ($null -eq $command) {
        $candidates = @($commands | Where-Object { $_ -like "$wordToComplete*" })
        if ($candidates.Count -gt 0) {
            $candidates += @(Get-ChildItem -Name -Path "$wordToComplete*" -ErrorAction SilentlyContinue)
        }
    }
    # Nothing to offer: PowerShell falls back to completing file names.
    $candidates | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}
"#;

/// The completion script for `shell`.
pub fn script(shell: Shell) -> &'static str {
    match shell {
        Shell::Bash => BASH,
        Shell::Zsh => ZSH,
        Shell::Fish => FISH,
        Shell::PowerShell => POWERSHELL,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scripts_cover_every_command_and_option() {
        for shell in [Shell::Bash, Shell::Zsh, Shell::Fish, Shell::PowerShell] {
            let s = script(shell);
            for cmd in crate::args::COMMANDS {
                assert!(s.contains(cmd), "{shell:?} lacks {cmd}");
            }
            for opt in [
                "config-dir",
                "headless",
                "framework",
                "junit",
                "system-dir",
                "log-dir",
                "disable-plugins",
                "software-rendering",
                "allowDefaults",
                "changes",
                "sarif",
                "UTF-16LE",
            ] {
                assert!(s.contains(opt), "{shell:?} lacks {opt}");
            }
        }
        assert!(script(Shell::Zsh).starts_with("#compdef rustpy"));
    }

    /// Syntax-checks the scripts with the shells that are installed.
    #[test]
    fn scripts_parse_in_their_shells() {
        let dir = tempfile::tempdir().unwrap();
        for (shell, exe, args) in [
            (Shell::Bash, "bash", vec!["-n"]),
            (Shell::Zsh, "zsh", vec!["-n"]),
            (Shell::Fish, "fish", vec!["--no-execute"]),
        ] {
            let Ok(path) = which(exe) else { continue };
            let file = dir.path().join(format!("rustpy.{exe}"));
            std::fs::write(&file, script(shell)).unwrap();
            let out = std::process::Command::new(path)
                .args(&args)
                .arg(&file)
                .output()
                .unwrap();
            assert!(
                out.status.success(),
                "{exe}: {}",
                String::from_utf8_lossy(&out.stderr)
            );
        }
    }

    /// Runs the bash completion function for some command lines.
    #[test]
    fn bash_completes_commands_options_and_values() {
        let Ok(bash) = which("bash") else { return };
        let dir = tempfile::tempdir().unwrap();
        // Keep the generated shell behavior while giving its probe an owned sink.
        let fixture = script(Shell::Bash).replace("/dev/null", "./completion-probe.log");
        std::fs::write(dir.path().join("rustpy.bash"), fixture).unwrap();
        std::fs::write(dir.path().join("project.py"), "").unwrap();
        let driver = r#"source ./rustpy.bash
c() { COMP_WORDS=("$@"); COMP_CWORD=$((${#COMP_WORDS[@]} - 1)); COMPREPLY=(); _rustpy; echo "${COMPREPLY[*]}"; }
c rustpy fo
c rustpy format -d
c rustpy inspect . x out -format ""
c rustpy --config-dir /tmp completions ""
c rustpy --w
c rustpy pro
c rustpy help me
"#;
        std::fs::write(dir.path().join("driver.sh"), driver).unwrap();
        let out = std::process::Command::new(bash)
            .arg("driver.sh")
            .current_dir(dir.path())
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        let lines: Vec<String> = String::from_utf8_lossy(&out.stdout)
            .lines()
            .map(str::to_string)
            .collect();
        assert_eq!(lines.len(), 7, "{lines:?}");
        assert_eq!(lines[0], "format");
        assert_eq!(lines[1], "-d -dry");
        assert_eq!(lines[2], "xml json plain sarif");
        assert_eq!(lines[3], "bash zsh fish powershell");
        assert_eq!(lines[4], "--wait");
        assert_eq!(lines[5], "project.py", "files and folders to open");
        assert_eq!(lines[6], "merge");
    }

    fn which(exe: &str) -> Result<std::path::PathBuf, ()> {
        let path = std::env::var_os("PATH").ok_or(())?;
        std::env::split_paths(&path)
            .map(|d| d.join(exe))
            .find(|p| p.is_file())
            .ok_or(())
    }
}
