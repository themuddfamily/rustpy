//! Spell checking for the RustPy IDE (roadmap §1 "Spell checking"): typos in
//! the identifiers, comments and string literals of Python files, and in
//! prose such as Markdown documents and commit messages.
//!
//! * [`Dictionary`]: the bundled English word list (plus standard-library
//!   vocabulary and programming jargon) and user/project words, with
//!   case-insensitive lookups that understand `camelCase` and `snake_case`,
//!   and "Change to…" suggestions ([`Dictionary::suggest`]).
//! * [`check_text`] / [`check_plain_text`]: the [`Typo`]s of a text, with byte
//!   ranges and suggestions.
//! * [`split_identifier`]: camel-case, snake-case and digit word splitting.
//! * [`load_user_words`], [`add_user_word`], [`remove_user_word`]: the
//!   persisted user dictionary ("Save to dictionary").
//!
//! ```
//! use rustpy_spell::{check_text, CheckOptions, Dictionary};
//!
//! let dict = Dictionary::bundled();
//! let typos = check_text("# Recieve the data\nx = 1\n", &dict, CheckOptions::default());
//! assert_eq!(typos[0].word, "Recieve");
//! assert_eq!(typos[0].suggestions[0], "Receive");
//! ```
//!
//! The bundled word list (`src/words.txt`, generated by
//! `tools/build_words.py`) is derived from dwyl/english-words (Unlicense) and
//! from the typeshed stubs (Apache-2.0); see `NOTICE.md`.

